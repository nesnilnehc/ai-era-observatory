"""Generate the static site and question documents from one reviewed data source."""
import argparse,json,pathlib,shutil,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
def products():
    raw=(ROOT/'data/observatory.json').read_text(); d=json.loads(raw)
    out={f'dist/{name}':(ROOT/'website'/name).read_text() for name in ('index.html','style.css','app.js')}
    out['dist/observatory.json']=raw
    for q in d['questions']:
        lines=[f"# {q['id']} · {q['title']}",'',f"观察视角：{q['lens']}。状态：{q['state']}。实质修订：{q['updated']}。",'',q['background'],'',q['scenario'],'','## 已核实的资料事实','']+['- '+x for x in q['known']]+['','## 未知','']+['- '+x for x in q['unknown']]+['','## 可比较的选项（本站研究提案）','']
        for o in q['options']:lines += [f"### {o['id']} · {o['title']}",'',o['action'],'',f"条件：{o['condition']}",'',f"代价与例外：{o['cost']}",'']
        lines+=['## 当前判断（本站分析）','',q['judgment'],'','## 改变判断的条件','',q['change_if'],'','## 下一步取证','',q['next'],'','## 相关来源','']
        for sid in q['refs']:
            s=next(x for x in d['sources'] if x['id']==sid);lines += [f"- [{sid} · {s['title']}]({s['url']})：{s['boundary']}"]
        lines+=['','<!-- Generated by scripts/build.py; edit data/observatory.json. -->','']
        out[f"questions/{q['id']}.md"]='\n'.join(lines)
    return out
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args();bad=[]
    for name,content in products().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=content:bad.append(name)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    if bad:print('Generated files differ: '+', '.join(bad));sys.exit(1)
    print('Generated files verified.' if args.check else 'Generated site and question documents.')
